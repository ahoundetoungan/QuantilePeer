# drop false isolated 
dropfis <- FALSE

# The following function takes an outcome and estimate the LIM, quantile-based, 
# and the CES models.
festim  <- function(outcome, nthreads) {
  cat("Outcome: ", outcome, "\n", sep = "")
  ########################################################
  ################### Data Preparation ###################
  ########################################################
  load(file = paste0(OutDataPath, "/", outcome, ".Rda")) # Load saved data using with the script 0-Data.R
  # Exogenous characteristics (excluding reference variables for identification)
  exovar  <- c("age", "age2", "grade", "grade2", "female", "hispanic", "racewhite", "raceblack", 
               "raceasian", "melhigh", "memhigh", "memiss", "mjprof", "mjother",  "mjmiss")
  # Exogenous characteristics used to compute instruments
  exovari <- c("age", "grade", "female", "hispanic", "racewhite", "raceblack", 
               "raceasian", "melhigh", "memhigh", "memiss", "mjprof", "mjother",  "mjmiss")
  y       <- data$y + 1 # + 1 because the CES-based model does not allow y <= 0
  X       <- as.matrix(data[,exovar])
  Xi      <- as.matrix(data[,exovari])
  nmatch  <- data$nmatch # Number of unmatched friends
  match   <- data$match  # Number of matched friends
  iso     <- match == 0 # Isolated in of observed network
  trueiso <- (match == 0 & nmatch == 0) # True isolated
  drop    <-  rep(FALSE, length(y)) # Observation to be dropped (we drop false isolated)
  if (dropfis) {
    drop  <- iso & !trueiso
  }
  Gnorm   <- norm.network(G) # Row-normalized network
  GX      <- peer.avg(Gnorm, X) 
  GXi     <- peer.avg(Gnorm, Xi)
  G2X     <- peer.avg(Gnorm, GX)  #G^2X: instrument in the standard LIM
  
  # I test three vectors for tau
  tau2    <- c(0, 1) # Two quantiles
  tau3    <- seq(0, 1, 1/2) # Three quantiles
  tau4    <- seq(0, 1, 1/3) # Four quantiles
  
  
  # Quantile of peer as instrument (like OLS)
  Qy2     <- qpeer.inst(formula = ~ y, A = G, tau = tau2, 
                        max.distance = 1, type = 7)$instruments
  
  Qy3     <- qpeer.inst(formula = ~y, A = G, tau = tau3, 
                        max.distance = 1, type = 7)$instruments
  
  Qy4     <- qpeer.inst(formula = ~y, A = G, tau = tau4, 
                        max.distance = 1, type = 7)$instruments
  
  # Quantile of X as instruments
  Z1      <- cbind(qpeer.inst(formula = ~ Xi, A = G, tau = seq(0, 1, 1/3), 
                              max.distance = 1, checkrank = TRUE, type = 7)$instruments,
                   qpeer.inst(formula = ~ GXi, A = G, tau = seq(0, 1, 1/3), 
                              max.distance = 1, checkrank = TRUE, type = 7)$instruments)
  
  X       <- cbind(X, nmatch = nmatch, match = match) # Adding additional variables
  # Exogenous prediction of y for the CES
  Zces    <- fitted(lm(y ~ X + GX + as.factor(data$SCID)))
  Zces[Zces <= 0] <- min(Zces[Zces > 0]) # Because z cannot be <= 0 for the CES-based model
  
  # Reduced number of instrument
  ## Predictors
  Z2      <- cbind(qpeer.inst(formula = ~ X, A = G, tau = seq(0, 1, 1/4), 
                              max.distance = 1, checkrank = TRUE, type = 7)$instruments,
                   qpeer.inst(formula = ~ GX, A = G, tau = seq(0, 1, 1/4), 
                              max.distance = 1, checkrank = TRUE, type = 7)$instruments)
  
  ## Random Forests
  ctl     <- list(num.trees = 1500,
                  replace = FALSE,
                  sample.fraction = 0.8,
                  num.threads = 8,
                  mtry = 2 * sqrt(ncol(X) + ncol(GX) + ncol(Z2)),
                  seed = 123)
  
  Z2      <- qpeer.cfit(formula = y ~ X + GX, 
                        excluded.instruments = ~ Z2, 
                        A = Gnorm,
                        fixed.effects = "separate",
                        estimator = "rf",
                        control = ctl,
                        nfold = 5,
                        tau = seq(0, 1, 1/9))
  
  #############################################################
  ######################### estimation ########################
  #############################################################
  # Linear model
  LIM     <- summary(linpeer(formula = y ~ X + GX, 
                             excluded.instruments = ~ G2X, 
                             A = Gnorm,
                             fixed.effects = "separate",
                             drop = drop,
                             HAC = "cluster"), 
                     diagnostics = TRUE)
  
  # Quantile models IV
  # tau2
  MQ2     <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ Z1, 
                   A = Gnorm,
                   fixed.effects = "separate",
                   tau = tau2,
                   type = 7,
                   drop = drop,
                   HAC = "cluster",
                   nthreads = nthreads)
  Q2      <- summary(MQ2, diagnostic = TRUE)
  
  # tau3
  MQ3     <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ Z1, 
                   A = Gnorm,
                   fixed.effects = "separate",
                   tau = tau3,
                   type = 7,
                   drop = drop,
                   HAC = "cluster",
                   nthreads = nthreads)
  Q3      <- summary(MQ3, diagnostic = TRUE)
  
  
  # tau4
  MQ4     <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ Z1, 
                   A = Gnorm,
                   fixed.effects = "separate",
                   tau = tau4,
                   type = 7,
                   drop = drop,
                   HAC = "cluster",
                   boot = 1e4,
                   nthreads = nthreads) 
  Q4      <- summary(MQ4, diagnostic = TRUE)
  
  # Cross-Fitting estimator
  # tau2
  JQ2      <- summary(qpeer(formula = y ~ X + GX, 
                            excluded.instruments = ~ Z2, 
                            A = Gnorm,
                            fixed.effects = "separate",
                            tau = tau2,
                            type = 7,
                            drop = drop,
                            HAC = "cluster",
                            nthreads = nthreads), diagnostic = TRUE)
  
  # tau3
  JQ3     <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Z2, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau3,
                           type = 7,
                           drop = drop,
                           HAC = "cluster",
                           nthreads = nthreads), diagnostic = TRUE)
  
  
  # tau4
  JQ4     <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Z2, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau4,
                           type = 7,
                           drop = drop,
                           HAC = "cluster",
                           boot = 1e4,
                           nthreads = nthreads), diagnostic = TRUE)
  
  # Quantile models OLS
  # tau2
  OLSQ2   <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Qy2, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau2,
                           type = 7,
                           drop = drop,
                           HAC = "cluster",
                           nthreads = nthreads))
  
  # tau3
  OLSQ3   <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Qy3, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau3,
                           type = 7,
                           drop = drop,
                           HAC = "cluster",
                           nthreads = nthreads))
  
  # tau4
  OLSQ4   <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Qy4, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau4,
                           type = 7,
                           drop = drop,
                           HAC = "cluster",
                           nthreads = nthreads))
  
  # Encompassing tests
  # The first test checks if the model with 3 quantiles replicates the features of the model with 4 quantiles.
  # The second test checks if the model with 4 quantiles replicates the features of the model with 5 quantiles.
  TEcomp  <- c("Test.ntau=2.3" = qpeer.test(MQ2, MQ3, which = "encompassing",
                                            boot = 1e4, nthreads = nthreads)$test["KP Wald rank", "p-value"],
               "Test.ntau=3.2" = qpeer.test(MQ3, MQ2, which = "encompassing",
                                            boot = 1e4, nthreads = nthreads)$test["KP Wald rank", "p-value"],
               "Test.ntau=3.4" = qpeer.test(MQ3, MQ4, which = "encompassing",
                                            boot = 1e4, nthreads = nthreads)$test["KP Wald rank", "p-value"])
  
  # Testing Monotonicity
  TM2     <- c(U = qpeer.test(MQ2, which = "uniform")$test["p-value"], 
               I = qpeer.test(MQ2, which = "increasing")$test["p-value"], 
               D = qpeer.test(MQ2, which = "decreasing")$test["p-value"])
  
  TM3     <- c(U = qpeer.test(MQ3, which = "uniform")$test["p-value"], 
               I = qpeer.test(MQ3, which = "increasing")$test["p-value"], 
               D = qpeer.test(MQ3, which = "decreasing")$test["p-value"])
  
  TM4     <- c(U = qpeer.test(MQ4, which = "uniform")$test["p-value"], 
               I = qpeer.test(MQ4, which = "increasing")$test["p-value"], 
               D = qpeer.test(MQ4, which = "decreasing")$test["p-value"])
  
  # CES
  CES     <- summary(cespeer(formula = y ~ X + GX, 
                             instrument = ~ Zces, 
                             A = Gnorm, 
                             fixed.effects = "separate",
                             drop = drop,
                             radius = 5,
                             grid.rho = seq(-100, 100, 1),
                             HAC = "cluster"))
  
  # Only non-isolated
  # LIM
  nILIM   <- summary(linpeer(formula = y ~ X + GX, 
                             excluded.instruments = ~ G2X, 
                             A = Gnorm,
                             fixed.effects = "separate",
                             HAC = "cluster",
                             drop = ifelse(match > 0, 0, 1)), # only non-isolated students
                     diagnostics = TRUE)
  
  # Quantile
  # tau2
  nIQ2    <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Z1, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau2,
                           type = 7,
                           HAC = "cluster",
                           nthreads = nthreads,
                           drop = ifelse(match > 0, 0, 1)), # only non-isolated students
                     diagnostics = TRUE)
  
  # tau3
  nIQ3    <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Z1, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau3,
                           type = 7,
                           HAC = "cluster",
                           nthreads = nthreads,
                           drop = ifelse(match > 0, 0, 1)), # only non-isolated students
                     diagnostics = TRUE)
  
  # tau4
  nIQ4    <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Z1, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau4,
                           type = 7,
                           HAC = "cluster",
                           nthreads = nthreads,
                           drop = ifelse(match > 0, 0, 1)), # only non-isolated students
                     diagnostics = TRUE)
  
  # CES
  nICES   <- summary(cespeer(formula = y ~ X + GX, 
                             instrument = ~ Zces, 
                             A = Gnorm, 
                             fixed.effects = "separate",
                             radius = 5,
                             grid.rho = seq(-100, 100, 1),
                             HAC = "cluster",
                             drop = ifelse(match > 0, 0, 1))) # only non-isolated students
  
  # Remove non-listed objects
  rm(list = setdiff(ls(), c("outcome", "depvar", "festim", "OutDataPath", "OutResPath", "dropfis",
                            "LIM", "Q2", "Q3", "Q4", "JQ2", "JQ3", "JQ4", "OLSQ2", "OLSQ3", "OLSQ4", "CES", 
                            "TEcomp", "TM2", "TM3", "TM4", "nILIM", "nIQ2", "nIQ3", "nIQ4", "nICES"))) 
  gc()
  
  # Save results
  save(LIM, Q2, Q3, Q4, OLSQ2, OLSQ3, OLSQ4, JQ2, JQ3, JQ4, TEcomp, TM2, TM3, TM4, CES,
       nILIM, nIQ2, nIQ3, nIQ4, nICES,
       file = paste0(OutResPath, "/", outcome, ".Rda"))
  NULL # Returns nothing, the results are directly saved
}

