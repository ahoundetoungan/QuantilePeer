# This function puts results together
# Argument k is the index of the outcome in depvar
fres <- function(k) {
  # Load results
  load(paste0(OutResPath, "/", depvar[k], ".Rda"))
  
  # For Tables 5.1 and 5.2
  ecol       <- c("Estimate", "Std. Error") 
  T5.1       <- rbind(NA, data.frame(cbind(
    t(Q3$coefficients[paste0("y_q", 1:3), ecol]), V1 = NA,
    LIM$coefficients["A:y", ecol], V2 = NA,
    t(CES$coefficients[c("rho", "A:y"), ecol])))  %>% 
      mutate(across(where(is.numeric), ~ ifelse(is.na(.), NA, sprintf("%.3f", .)))) %>%  # Ensures exactly 3 decimals
      mutate(across(everything(), ~ ifelse(
        is.na(.), NA,
        ifelse(row_number() %% 2 == 0, paste0("(", trimws(.), ")"), .)
      ))))  # Parentheses without spaces 
  T5.1[1, 1] <- OUTCOME[k]
  
  T5.2       <- rbind(NA, data.frame(cbind(
    rbind(t(TEcomp[c("Test.ntau=2.3", "Test.ntau=3.4")]), NA), NA, # Encompassing test,
    rbind(Q3$diagnostics[paste0("Weak instruments (y_q", 1:3, ")"), "statistic"], NA), NA, # F stat
    rbind(Q3$diagnostics["Kleibergen-Paap rk Wald", "p-value"], NA), NA, # KP rank stat
    rbind(TM3, NA) # Monotonicity test
  )) %>%  
    mutate(across(-c(4:6), ~ ifelse(is.na(.), NA, sprintf("%.3f", .))), # Ensures exactly 3 decimals
           across(4:6, ~ ifelse(is.na(.), NA, sprintf("%.0f", .)))) %>% # Ensures no decimals 
    filter(row_number() != 2))
  T5.2[1, 1] <- OUTCOME[k]
  
  # Sample size TE.1
  TE.1       <- data.frame(V1 = OUTCOME[k], n = Q4$model.info$n)
  
  # Table E.2 Cross fitting and no Isolated
  TE.2       <- rbind(NA, data.frame(cbind(
    t(JQ3$coefficients[paste0("y_q", 1:3), ecol]), V1 = NA,
    t(nIQ3$coefficients[paste0("y_q", 1:3), ecol])))  %>% 
      mutate(across(where(is.numeric), ~ ifelse(is.na(.), NA, sprintf("%.3f", .)))) %>%  # Ensures exactly 3 decimals
      mutate(across(everything(), ~ ifelse(
        is.na(.), NA,
        ifelse(row_number() %% 2 == 0, paste0("(", trimws(.), ")"), .)
      ))))  # Parentheses without spaces 
  TE.2[1, 1] <- OUTCOME[k]
  
  # Table E.3 (4 quantiles)
  TE.3       <- rbind(NA, data.frame(cbind(
    t(Q4$coefficients[paste0("y_q", 1:4), ecol])))  %>% 
      mutate(across(where(is.numeric), ~ ifelse(is.na(.), NA, sprintf("%.3f", .)))) %>%  # Ensures exactly 3 decimals
      mutate(across(everything(), ~ ifelse(
        is.na(.), NA,
        ifelse(row_number() %% 2 == 0, paste0("(", trimws(.), ")"), .)
      ))))  # Parentheses without spaces 
  TE.3[1, 1] <- OUTCOME[k]
  
  
  # Full results
  ecol    <- c("Estimate", "Std. Error", "Pr(>|t|)") 
  # Quantile model
  Qtl     <- list()
  for (x in 2:4) {
    Q        <- get(paste0("Q", x))
    JQ       <- get(paste0("JQ", x))
    nIQ      <- get(paste0("nIQ", x))
    
    # Standard IV
    Q      <- rbind(t(Q$coefficients[paste0("y_q", 1:x), ecol]),
                    t(Q$diagnostics[paste0("Weak instruments (y_q", 1:x, ")"), "statistic"]),
                    t(c(Q$diagnostics[paste0("Kleibergen-Paap rk Wald"), "statistic"], rep(NA, x - 1))), 
                    t(c(Q$diagnostics[paste0("Kleibergen-Paap rk Wald"), "df1"], rep(NA, x - 1))),
                    t(c(Q$diagnostics[paste0("Kleibergen-Paap rk Wald"), "p-value"], rep(NA, x - 1))),
                    matrix(NA, 2, x))
    
    # Cross fitting
    JQ     <- rbind(t(JQ$coefficients[paste0("y_q", 1:x), ecol]),
                    t(JQ$diagnostics[paste0("Weak instruments (y_q", 1:x, ")"), "statistic"]),
                    t(c(JQ$diagnostics[paste0("Kleibergen-Paap rk Wald"), "statistic"], rep(NA, x - 1))), 
                    t(c(JQ$diagnostics[paste0("Kleibergen-Paap rk Wald"), "df1"], rep(NA, x - 1))),
                    t(c(JQ$diagnostics[paste0("Kleibergen-Paap rk Wald"), "p-value"], rep(NA, x - 1))),
                    matrix(NA, 2, x))
    
    # Without isolates
    nIQ    <- rbind(t(nIQ$coefficients[paste0("y_q", 1:x), ecol]),
                    t(nIQ$diagnostics[paste0("Weak instruments (y_q", 1:x, ")"), "statistic"]),
                    t(c(nIQ$diagnostics[paste0("Kleibergen-Paap rk Wald"), "statistic"], rep(NA, x - 1))), 
                    t(c(nIQ$diagnostics[paste0("Kleibergen-Paap rk Wald"), "df1"], rep(NA, x - 1))),
                    t(c(nIQ$diagnostics[paste0("Kleibergen-Paap rk Wald"), "p-value"], rep(NA, x - 1))),
                    matrix(NA, 2, x))
    
    # Monotonocity
    Tmo    <- rbind(t(get(paste0("TM", x))),
                    matrix(NA, 8, 3))
    
    # Put result together
    Qtlx    <- NULL
    
    if (x == 3) {
      # Encompassing test
      Tec  <- rbind(t(TEcomp),
                    matrix(NA, 8, 3))
      Qtlx <- cbind(Q, Id = NA, Tmo, Id = NA, Tec, Id = NA, JQ, Id = NA, nIQ, Id = NA)
    } else {
      Qtlx <- cbind(Q, Id = NA, Tmo, Id = NA, JQ, Id = NA, nIQ, Id = NA)
    }
    Qtl[[x - 1]]  <- Qtlx
  }
  
  # LIM
  # Full data
  LM        <- rbind(t(LIM$coefficients["A:y", ecol, drop = FALSE]),
                     matrix(NA, 6, 1))
  
  # Without isolates
  nILM      <- rbind(t(nILIM$coefficients["A:y", ecol, drop = FALSE]),
                     matrix(NA, 6, 1))
  
  # CES
  # Full data
  CES       <- rbind(t(CES$coefficients[c("rho", "A:y"), ecol]),
                     matrix(NA, 6, 2))
  
  # Without isolates
  nICES     <- rbind(t(nICES$coefficients[c("rho", "A:y"), ecol]),
                     matrix(NA, 6, 2))
  
  out           <- cbind(Id = NA, Id = NA, do.call(cbind, Qtl), LM, Id = NA, nILM, 
                         Id = NA, CES, Id = NA, nICES)
  tp            <- matrix(NA, 1, ncol(out))
  out           <- as.data.frame(rbind(tp, out, tp))
  out[1, 1]     <- OUTCOME[k]
  out[2:10, 2]  <- c("Coef", "StD", "Prob", "F Stat",
                     "KP rk - Stat", "KP rk - df", "KP rk - pvalue", 
                     "Exo Z2 Sargan", "Exo Z2 Wald")
  list(T5.1 = T5.1, T5.2 = T5.2, 
       TE.1 = TE.1, TE.2 = TE.2, TE.3 = TE.3, Full = out)
}

