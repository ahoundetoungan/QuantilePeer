dropfis <- FALSE

# The following function takes an outcome and estimate the LIM, quantile-based, 
# and the CES models.
festim  <- function(outcome, nthreads) {
  cat("Outcome: ", outcome, "\n", sep = "")
  ########################################################
  ################### Data Preparation ###################
  ########################################################
  load(file = paste0(OutDataPath, "/", outcome, ".Rda")) # Load saved data using with the script 0-Data.R
  # Exogenous characteristics (excluding reference variables for identification)
  exovar  <- c("age", "age2", "grade", "grade2", "female", "hispanic", "racewhite", "raceblack", 
               "raceasian", "melhigh", "memhigh", "memiss", "mjprof", "mjother",  "mjmiss")
  y       <- data$y + 1 # + 1 because the CES-based model does not allow y <= 0
  X       <- as.matrix(data[,exovar])
  nmatch  <- data$nmatch # Number of unmatched friends
  match   <- data$match  # Number of matched friends
  iso     <- match == 0 # Isolated in of observed network
  trueiso <- (match == 0 & nmatch == 0) # True isolated
  drop    <-  rep(FALSE, length(y)) # Observation to be dropped (we drop false isolated)
  if (dropfis) {
    drop  <- iso & !trueiso
  }
  Gnorm   <- norm.network(G) # Row-normalized network
  GX      <- peer.avg(Gnorm, X) 
  G2X     <- peer.avg(Gnorm, GX)  #G^2X: instrument in the standard LIM
  
  # I test three vectors for tau
  tau3    <- seq(0, 1, 1/2) # Three quantiles
  tau4    <- seq(0, 1, 1/3) # Four quantiles
  tau5    <- seq(0, 1, 1/4) # Five quantiles
  
  # Quantile of peer as instrument (like OLS)
  Qy3     <- qpeer.inst(formula = ~y, A = G, tau = tau3, 
                        max.distance = 1, type = 7)$instruments
  
  Qy4     <- qpeer.inst(formula = ~y, A = G, tau = tau4, 
                        max.distance = 1, type = 7)$instruments
  
  Qy5     <- qpeer.inst(formula = ~y, A = G, tau = tau5, 
                        max.distance = 1, type = 7)$instruments
  
  # Quantile of X instruments
  ZQ      <- cbind(qpeer.inst(formula = ~ X + GX, A = G, tau = seq(0, 1, 1/9), 
                              max.distance = 2, checkrank = TRUE, type = 7)$instruments)
  
  X       <- cbind(X, nmatch = nmatch, match = match) # Adding additional variables
  # Exogenous prediction of y for the CES
  Zces    <- fitted(lm(y ~ X + GX + as.factor(data$SCID)))
  Zces[Zces <= 0] <- min(Zces[Zces > 0]) # Because z cannot be <= 0 for the CES-based model
  
  #############################################################
  ######################### estimation ########################
  #############################################################
  # Linear model
  LIM     <- summary(linpeer(formula = y ~ X + GX, 
                             excluded.instruments = ~ G2X, 
                             A = Gnorm,
                             fixed.effects = "separate",
                             drop = drop,
                             HAC = "cluster"), 
                     diagnostics = TRUE)
  
  # Quantile models IV
  # tau3
  MQ3     <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ ZQ, 
                   A = Gnorm,
                   fixed.effects = "separate",
                   tau = tau3,
                   type = 7,
                   drop = drop,
                   HAC = "cboot",
                   boot = 1e4,
                   nthreads = nthreads)
  Q3      <- summary(MQ3)
  
  # tau4
  MQ4     <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ ZQ, 
                   A = Gnorm,
                   fixed.effects = "separate",
                   tau = tau4,
                   type = 7,
                   drop = drop,
                   HAC = "cboot",
                   boot = 1e4,
                   nthreads = nthreads)
  Q4      <- summary(MQ4)
  
  # Uncluttered
  Q4u     <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ ZQ, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau4,
                           type = 7,
                           drop = drop), diagnostics = TRUE)
  
  # tau5
  MQ5     <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ ZQ, 
                   A = Gnorm,
                   fixed.effects = "separate",
                   tau = tau5,
                   type = 7,
                   drop = drop,
                   HAC = "cboot",
                   boot = 1e4,
                   nthreads = nthreads) 
  Q5      <- summary(MQ5)
  
  
  # Quantile models OLS
  # tau3
  OLSQ3   <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Qy3, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau3,
                           type = 7,
                           drop = drop,
                           HAC = "cluster",
                           nthreads = nthreads))
  
  # tau4
  OLSQ4   <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Qy4, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau4,
                           type = 7,
                           drop = drop,
                           HAC = "cluster",
                           nthreads = nthreads))
  
  # tau5
  OLSQ5   <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Qy5, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau4,
                           type = 7,
                           drop = drop,
                           HAC = "cluster",
                           nthreads = nthreads))
  
  # Encompassing tests
  # The first test checks if the model with 3 quantiles replicates the features of the model with 4 quantiles.
  # The second test checks if the model with 4 quantiles replicates the features of the model with 5 quantiles.
  TEcomp  <- c("Test.ntau=3.4" = qpeer.test(MQ3, MQ4, which = "encompassing",
                                            boot = 1e4, nthreads = nthreads)$test["KP Wald rank", "p-value"],
               "Test.ntau=4.3" = qpeer.test(MQ4, MQ3, which = "encompassing",
                                            boot = 1e4, nthreads = nthreads)$test["KP Wald rank", "p-value"],
               "Test.ntau=4.5" = qpeer.test(MQ4, MQ5, which = "encompassing",
                                            boot = 1e4, nthreads = nthreads)$test["KP Wald rank", "p-value"])
  
  # Testing Monotonicity
  TM3     <- c(U = qpeer.test(MQ3, which = "uniform")$test["p-value"], 
               I = qpeer.test(MQ3, which = "increasing")$test["p-value"], 
               D = qpeer.test(MQ3, which = "decreasing")$test["p-value"])
  
  TM4     <- c(U = qpeer.test(MQ4, which = "uniform")$test["p-value"], 
               I = qpeer.test(MQ4, which = "increasing")$test["p-value"], 
               D = qpeer.test(MQ4, which = "decreasing")$test["p-value"])
  
  TM5     <- c(U = qpeer.test(MQ5, which = "uniform")$test["p-value"], 
               I = qpeer.test(MQ5, which = "increasing")$test["p-value"], 
               D = qpeer.test(MQ5, which = "decreasing")$test["p-value"])
  
  # CES
  CES     <- summary(cespeer(formula = y ~ X + GX, 
                             instrument = ~ Zces, 
                             A = Gnorm, 
                             fixed.effects = "separate",
                             drop = drop,
                             radius = 5,
                             grid.rho = seq(-100, 100, 1),
                             HAC = "cluster"))
  
  # Only isolated
  # LIM
  nILIM   <- summary(linpeer(formula = y ~ X + GX, 
                             excluded.instruments = ~ G2X, 
                             A = Gnorm,
                             fixed.effects = "separate",
                             HAC = "cluster",
                             drop = ifelse(match > 0, 0, 1)), # only isolated students
                     diagnostics = TRUE)
  
  # Quantile
  # tau3
  nIQ3    <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ ZQ, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau3,
                           type = 7,
                           HAC = "cboot",
                           boot = 1e4,
                           nthreads = nthreads,
                           drop = ifelse(match > 0, 0, 1))) # only isolated students
  
  # tau4
  nIQ4    <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ ZQ, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau4,
                           type = 7,
                           HAC = "cboot",
                           boot = 1e4,
                           nthreads = nthreads,
                           drop = ifelse(match > 0, 0, 1))) # only isolated students
  
  # tau5
  nIQ5    <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ ZQ, 
                           A = Gnorm,
                           fixed.effects = "separate",
                           tau = tau5,
                           type = 7,
                           HAC = "cboot",
                           boot = 1e4,
                           nthreads = nthreads,
                           drop = ifelse(match > 0, 0, 1))) # only isolated students
  
  # CES
  nICES   <- summary(cespeer(formula = y ~ X + GX, 
                             instrument = ~ Zces, 
                             A = Gnorm, 
                             fixed.effects = "separate",
                             radius = 5,
                             grid.rho = seq(-100, 100, 1),
                             HAC = "cluster",
                             drop = ifelse(match > 0, 0, 1))) # only isolated students
  
  # Remove non-listed objects
  rm(list = setdiff(ls(), c("outcome", "depvar", "festim", "OutDataPath", "OutResPath", "dropfis",
                            "LIM", "Q3", "Q4", "Q4u", "Q5", "OLSQ3", "OLSQ4", "OLSQ5", "CES", 
                            "TEcomp", "TM3", "TM4", "TM5", "nILIM", "nIQ3", "nIQ4", "nIQ5", "nICES"))) 
  gc()
  
  # Save results
  save(LIM, Q3, Q4, Q4u, Q5, OLSQ3, OLSQ4, OLSQ5, TEcomp, TM3, TM4, TM5, CES,
       nILIM, nIQ3, nIQ4, nIQ5, nICES,
       file = paste0(OutResPath, "/", outcome, ".Rda"))
  NULL # Returns nothing, the results are directly saved
}

