# This function puts results together
# Argument k is the index of the outcome in depvar
fres <- function(k) {
  # Load results
  load(paste0(OutResPath, "/", depvar[k], ".Rda"))
  
  # For Tables 5.1 and 5.2
  ecol       <- c("Estimate", "Std. Error") 
  T5.1       <- rbind(NA, data.frame(cbind(
    t(Q4$coefficients[paste0("y_q", 1:4), ecol]), V1 = NA,
    LIM$coefficients["A:y", ecol], V2 = NA,
    t(CES$coefficients[c("rho", "A:y"), ecol])))  %>% 
      mutate(across(where(is.numeric), ~ ifelse(is.na(.), NA, sprintf("%.3f", .)))) %>%  # Ensures exactly 3 decimals
      mutate(across(everything(), ~ ifelse(
        is.na(.), NA,
        ifelse(row_number() %% 2 == 0, paste0("(", trimws(.), ")"), .)
      ))))  # Parentheses without spaces 
  T5.1[1, 1] <- OUTCOME[k]
  
  T5.2       <- rbind(NA, data.frame(cbind(
    rbind(t(TEcomp[c("Test.ntau=3.4", "Test.ntau=4.5")]), NA), NA, # Encompassing, ntau = 4 against ntau = 5  
    rbind(Q4u$diagnostics[paste0("Kleibergen-Paap rk Wald"), "p-value"], NA), NA, # KP rank stat
    rbind(TM4, NA) # Monotonicity test
  )) %>%  
    mutate(across(where(is.numeric), ~ ifelse(is.na(.), NA, sprintf("%.3f", .)))) %>%  # Ensures exactly 3 decimals
    filter(row_number() != 2))
  T5.2[1, 1] <- OUTCOME[k]
  
  # Sample size TE.1
  TE.1       <- data.frame(V1 = OUTCOME[k], n = Q4$model.info$n)
  
  # Table E.2 (5 quantiles)
  TE.2       <- rbind(NA, data.frame(cbind(
    t(Q5$coefficients[paste0("y_q", 1:5), ecol]), V1 = NA,
    t(nIQ4$coefficients[paste0("y_q", 1:4), ecol])))  %>% 
      mutate(across(where(is.numeric), ~ ifelse(is.na(.), NA, sprintf("%.3f", .)))) %>%  # Ensures exactly 3 decimals
      mutate(across(everything(), ~ ifelse(
        is.na(.), NA,
        ifelse(row_number() %% 2 == 0, paste0("(", trimws(.), ")"), .)
      ))))  # Parentheses without spaces 
  TE.2[1, 1] <- OUTCOME[k]
  
  
  # Table E.3 OLS (4 quantiles)
  TE.3       <- rbind(NA, data.frame(cbind(
    t(OLSQ4$coefficients[paste0("y_q", 1:4), ecol]), V1 = NA,
    t(nIQ4$coefficients[paste0("y_q", 1:4), ecol]), V2 = NA,
    c(Q4u$diagnostics["Wu-Hausman", "p-value"], NA)))  %>% 
      mutate(across(where(is.numeric), ~ ifelse(is.na(.), NA, sprintf("%.3f", .)))) %>%  # Ensures exactly 3 decimals
      mutate(across(everything(), ~ ifelse(
        is.na(.), NA,
        ifelse(row_number() %% 2 == 0, paste0("(", trimws(.), ")"), .)
      ))))  # Parentheses without spaces 
  TE.3[1, 1] <- OUTCOME[k]
  
  # Full results (do not include OLS)
  ecol    <- c("Estimate", "Std. Error", "Pr(>|t|)") 
  # Quantile model
  Qtl     <- list()
  for (x in 3:5) {
    Q        <- get(paste0("Q", x))
    nIQ      <- get(paste0("nIQ", x))
    if (x %in% 4) { # because diagnostics are available
      Qu     <- get(paste0("Q", x, "u"))
      # Full data
      Q      <- rbind(t(Q$coefficients[paste0("y_q", 1:x), ecol]),
                      t(c(Qu$diagnostics[paste0("Kleibergen-Paap rk Wald"), "statistic"], rep(NA, x - 1))), 
                      t(c(Qu$diagnostics[paste0("Kleibergen-Paap rk Wald"), "df1"], rep(NA, x - 1))),
                      t(c(Qu$diagnostics[paste0("Kleibergen-Paap rk Wald"), "p-value"], rep(NA, x - 1))),
                      matrix(NA, 2, x))
      
      # Without isolates
      nIQ    <- rbind(t(nIQ$coefficients[paste0("y_q", 1:x), ecol]),
                      matrix(NA, 5, x))
    } else {
      # Full data
      Q      <- rbind(t(Q$coefficients[paste0("y_q", 1:x), ecol]),
                      matrix(NA, 5, x))
      
      # Without isolates
      nIQ    <- rbind(t(nIQ$coefficients[paste0("y_q", 1:x), ecol]),
                      matrix(NA, 5, x))
    }
    
    
    # Monotonocity
    Tmo    <- rbind(t(get(paste0("TM", x))),
                    matrix(NA, 7, 3))
    
    # Put result together
    Qtlx    <- NULL
    
    if (x == 4) {
      # Encompassing test
      Tec  <- rbind(t(TEcomp),
                    matrix(NA, 7, 3))
      Qtlx <- cbind(Q, Id = NA, Tmo, Id = NA, Tec, Id = NA, nIQ, Id = NA)
    } else {
      Qtlx <- cbind(Q, Id = NA, Tmo, Id = NA, nIQ, Id = NA)
    }
    Qtl[[x - 2]]  <- Qtlx
  }
  
  # LIM
  # Full data
  LM        <- rbind(t(LIM$coefficients["A:y", ecol, drop = FALSE]),
                     matrix(NA, 5, 1))
  
  # Without isolates
  nILM      <- rbind(t(nILIM$coefficients["A:y", ecol, drop = FALSE]),
                     matrix(NA, 5, 1))
  
  # CES
  # Full data
  CES       <- rbind(t(CES$coefficients[c("rho", "A:y"), ecol]),
                     matrix(NA, 5, 2))
  
  # Without isolates
  nICES     <- rbind(t(nICES$coefficients[c("rho", "A:y"), ecol]),
                     matrix(NA, 5, 2))
  
  out           <- cbind(Id = NA, Id = NA, do.call(cbind, Qtl), LM, Id = NA, nILM, 
                         Id = NA, CES, Id = NA, nICES)
  tp            <- matrix(NA, 1, ncol(out))
  out           <- as.data.frame(rbind(tp, out, tp))
  out[1, 1]     <- OUTCOME[k]
  out[2:9, 2]  <- c("Mean", "StD", "Prob", 
                    "KP rk - Stat", "KP rk - df", "KP rk - pvalue", 
                    "Exo Z2 Sargan", "Exo Z2 Wald")
  list(T5.1 = T5.1, T5.2 = T5.2, 
       TE.1 = TE.1, TE.2 = TE.2, TE.3 = TE.3, Full = out)
}

