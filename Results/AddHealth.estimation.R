# All estimation results are exported into a single Excel file (`Estimation.xlsx`)
# located in OutResPath. The Excel contains has the following sheets:
#  - Table 6.1 (reproduces Table 6.1),
#  - Table 6.2 (reproduces Table 6.2),
#  - Full results (not included in the paper).

