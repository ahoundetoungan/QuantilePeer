dropfis <- TRUE

# The following function takes an outcome and estimate the LIM, quantile-based, and the CES models.
festim  <- function(outcome) {
  cat("Outcome: ", outcome, "\n", sep = "")
  ########################################################
  ################### Data Preparation ###################
  ########################################################
  load(file = paste0(OutDataPath, outcome, ".Rda")) # Load saved data using with the script 0-Data.R
  # Exogenous characteristics (excluding reference variables for identification)
  exovar  <- c("age", "age2", "grade", "grade2", "female", "hispanic", "racewhite", "raceblack", 
               "raceasian", "melhigh", "memhigh", "memiss", "mjprof", "mjother",  "mjmiss")
  y       <- data$y + 1 # + 1 because the CES-based model does not allow y <= 0
  X       <- as.matrix(data[,exovar])
  nmatch  <- data$nmatch # Number of unmatched friends
  match   <- data$match  # Number of matched friends
  iso     <- match == 0 # Isolated in of observed network
  trueiso <- (match == 0 & nmatch == 0) # True isolated
  drop    <-  rep(FALSE, length(y)) # Observation to be dropped
  if (dropfis) {
    drop  <- iso & !trueiso
  }
  Gnorm   <- norm.network(G) # Row-normalized network
  GX      <- peer.avg(Gnorm, X) 
  G2X     <- peer.avg(Gnorm, GX)  #G^2X: instrument in the standard LIM
  
  # I test three vectors for tau
  tau3    <- seq(0, 1, 1/2) # Three quantiles
  tau4    <- seq(0, 1, 1/3) # Four quantiles
  tau5    <- seq(0, 1, 1/4) # Five quantiles
  
  # First type of instruments
  Z1      <- cbind(qpeer.inst(formula = ~ X + GX, Glist = G, tau = seq(0, 1, 1/9), 
                              max.distance = 2, checkrank = TRUE, type = 7)$instruments)
  # Second type of instruments with tau3
  Z23     <- qpeer.inst(formula = y ~ X + GX, Glist = G, tau = tau3,
                        max.distance = 2, checkrank = TRUE, type = 7)$instruments
  # Second type of instruments with tau4
  Z24     <- qpeer.inst(formula = y ~ X + GX, Glist = G, tau = tau4,
                        max.distance = 2, checkrank = TRUE, type = 7)$instruments
  # Second type of instruments with tau5
  Z25     <- qpeer.inst(formula = y ~ X + GX, Glist = G, tau = tau5,
                        max.distance = 2, checkrank = TRUE, type = 7)$instruments
  X       <- cbind(X, nmatch = nmatch, match = match) # Adding additional variables
  # Exogenous prediction of y for the CES
  Zces    <- fitted(lm(y ~ X + GX + as.factor(data$SCID)))
  Zces[Zces <= 0] <- min(Zces[Zces > 0]) # Because z cannot be <= 0 for the CES-based model
  
  #############################################################
  ################### Structural estimation ###################
  #############################################################
  # Linear model
  SLIM    <- summary(linpeer(formula = y ~ X + GX, 
                             excluded.instruments = ~ G2X, 
                             Glist = Gnorm,
                             fixed.effects = "separate",
                             drop = drop,
                             structural = TRUE), 
                     diagnostics = TRUE)
  
  # Only Z1 as instruments
  # tau3
  MSQ13   <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ Z1, 
                   Glist = Gnorm,
                   fixed.effects = "separate",
                   drop = drop,
                   tau = tau3,
                   type = 7, # Type 7 quantile
                   structural = TRUE)
  SQ13    <- summary(MSQ13)
  
  # tau4
  MSQ14   <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ Z1, 
                   Glist = Gnorm,
                   fixed.effects = "separate",
                   drop = drop,
                   tau = tau4,
                   type = 7, # Type 7 quantile
                   structural = TRUE)
  SQ14    <- summary(MSQ14, diagnostics = TRUE) # Diagnostics for tau4 only
  
  # tau5
  MSQ15   <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ Z1, 
                   Glist = Gnorm,
                   fixed.effects = "separate",
                   drop = drop,
                   tau = tau5,
                   type = 7, # Type 7 quantile
                   structural = TRUE)
  SQ15    <- summary(MSQ15)
  
  # Encompassing tests
  # The first test checks if the model with 3 quantiles replicates the features of the model with 4 quantiles.
  # The second test checks if the model with 4 quantiles replicates the features of the model with 5 quantiles.
  TEcomp  <- c("Test.ntau=3.4" = qpeer.test(MSQ13, MSQ14, which = "encompassing")$test["KP Wald rank", "p-value"],
               "Test.ntau=4.3" = qpeer.test(MSQ14, MSQ13, which = "encompassing")$test["KP Wald rank", "p-value"],
               "Test.ntau=4.5" = qpeer.test(MSQ14, MSQ15, which = "encompassing")$test["KP Wald rank", "p-value"])
  
  # Testing Monotonicity
  TM13    <- c(U = qpeer.test(MSQ13, which = "uniform")$test["p-value"], 
               I = qpeer.test(MSQ13, which = "increasing")$test["p-value"], 
               D = qpeer.test(MSQ13, which = "decreasing")$test["p-value"])
  
  TM14    <- c(U = qpeer.test(MSQ14, which = "uniform")$test["p-value"], 
               I = qpeer.test(MSQ14, which = "increasing")$test["p-value"], 
               D = qpeer.test(MSQ14, which = "decreasing")$test["p-value"])
  
  TM15    <- c(U = qpeer.test(MSQ15, which = "uniform")$test["p-value"], 
               I = qpeer.test(MSQ15, which = "increasing")$test["p-value"], 
               D = qpeer.test(MSQ15, which = "decreasing")$test["p-value"])
  
  # Adding supplementary instruments (type 2 instruments)
  # tau3
  MSQ23   <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ Z1 + Z23, 
                   Glist = Gnorm,
                   fixed.effects = "separate",
                   drop = drop,
                   tau = tau3,
                   type = 7, # Type 7 quantile
                   structural = TRUE)
  SQ23    <- summary(MSQ23)
  
  # tau4
  MSQ24   <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ Z1 + Z24, 
                   Glist = Gnorm,
                   fixed.effects = "separate",
                   drop = drop,
                   tau = tau4,
                   type = 7, # Type 7 quantile
                   structural = TRUE)
  SQ24    <- summary(MSQ24, diagnostics = TRUE) # diagnostic for tau4 only
  
  # tau5
  MSQ25   <- qpeer(formula = y ~ X + GX, 
                   excluded.instruments = ~ Z1 + Z25, 
                   Glist = Gnorm,
                   fixed.effects = "separate",
                   drop = drop,
                   tau = tau5,
                   type = 7, # Type 7 quantile
                   structural = TRUE)
  SQ25    <- summary(MSQ25)
  
  # Testing exogeneity of type 2 instruments
  TVSQ23  <- c(W = qpeer.test(MSQ13, MSQ23, which = "sargan")$test["p-value"],
               S = qpeer.test(MSQ13, MSQ23, which = "wald")$test["p-value"])
  TVSQ24  <- c(W = qpeer.test(MSQ14, MSQ24, which = "sargan")$test["p-value"],
               S = qpeer.test(MSQ14, MSQ24, which = "wald")$test["p-value"])
  TVSQ25  <- c(W = qpeer.test(MSQ15, MSQ25, which = "sargan")$test["p-value"],
               S = qpeer.test(MSQ15, MSQ25, which = "wald")$test["p-value"])
  
  # CES
  SCES    <- summary(cespeer(formula = y ~ X + GX, 
                             instrument = ~ Zces, 
                             Glist = Gnorm, 
                             structural = TRUE,
                             fixed.effects = "separate",
                             drop = drop, 
                             radius = 5,
                             grid.rho = seq(-100, 100, 1)))
  
  # Only isolated
  # LIM
  nIRLIM  <- summary(linpeer(formula = y ~ X + GX, 
                             excluded.instruments = ~ G2X, 
                             Glist = Gnorm,
                             fixed.effects = "separate",
                             drop = ifelse(match > 0, 0, 1), # only isolated students
                             structural = FALSE), 
                     diagnostics = TRUE)
  
  # Quantile
  # tau3
  nIRQ13  <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Z1, 
                           Glist = Gnorm,
                           fixed.effects = "separate",
                           drop = ifelse(match > 0, 0, 1), # only isolated students
                           tau = tau3,
                           type = 7, # Type 7 quantile
                           structural = FALSE))
  
  # tau4
  nIRQ14  <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Z1, 
                           Glist = Gnorm,
                           fixed.effects = "separate",
                           drop = ifelse(match > 0, 0, 1), # only isolated students
                           tau = tau4,
                           type = 7, # Type 7 quantile
                           structural = FALSE), diagnostics = TRUE)
  
  # tau5
  nIRQ15  <- summary(qpeer(formula = y ~ X + GX, 
                           excluded.instruments = ~ Z1, 
                           Glist = Gnorm,
                           fixed.effects = "separate",
                           drop = ifelse(match > 0, 0, 1), # only isolated students
                           tau = tau5,
                           type = 7, # Type 7 quantile
                           structural = FALSE))
  
  # CES
  nIRCES  <- summary(cespeer(formula = y ~ X + GX, 
                             instrument = ~ Zces, 
                             Glist = Gnorm, 
                             structural = FALSE,
                             fixed.effects = "separate",
                             drop = ifelse(match > 0, 0, 1), # only isolated students
                             radius = 5,
                             grid.rho = seq(-100, 100, 1)))
  
  # Remove non-listed objects
  rm(list = setdiff(ls(), c("outcome", "depvar", "festim", "OutDataPath", "OutResPath", "dropfis",
                            "SLIM", "SQ13", "SQ14", "SQ15", "TEcomp", "TM13", "TM14", "TM15",  
                            "SQ23", "SQ24", "SQ25", "TVSQ23", "TVSQ24", "TVSQ25", "SCES",
                            "nIRLIM", "nIRQ13", "nIRQ14", "nIRQ15", "nIRCES"))) 
  gc()
  
  # Save results
  save(SLIM, SQ13, SQ14, SQ15, TEcomp, TM13, TM14, TM15,  
       SQ23, SQ24, SQ25, TVSQ23, TVSQ24, TVSQ25, SCES,
       nIRLIM, nIRQ13, nIRQ14, nIRQ15, nIRCES,
       file = paste0(OutResPath, outcome, ".Rda"))
  NULL # Returns nothing, the results are directly saved
}

