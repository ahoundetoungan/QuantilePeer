# This function puts results together
# Argument k is the index of the outcome in depvar
fres <- function(k) {
  # Load results
  load(paste0(OutResPath, depvar[k], ".Rda"))
  
  # For Tables 6.1 and 6.2
  ecol       <- c("Estimate", "Std. Error") 
  T6.1       <- rbind(NA, data.frame(cbind(
    t(SQ14$coefficients[c(paste0("y_q", 1:4), "y_q(spillover)", "y_q(conformity)"), ecol]), V1 = NA,
    t(SLIM$coefficients[c("G(spillover):y", "G(conformity):y"), ecol]), V2 = NA,
    t(SCES$coefficients[c("rho", "G(spillover):y", "G(conformity):y"), ecol])))  %>% 
      mutate(across(where(is.numeric), ~ ifelse(is.na(.), NA, sprintf("%.3f", .)))) %>%  # Ensures exactly 3 decimals
      mutate(across(everything(), ~ ifelse(
        is.na(.), NA,
        ifelse(row_number() %% 2 == 0, paste0("(", trimws(.), ")"), .)
      ))))  # Parentheses without spaces 
  T6.1[1, 1] <- OUTCOME[k]
  
  T6.2       <- rbind(NA, data.frame(cbind(
    t(nIRQ14$coefficients[paste0("y_q", 1:4), ecol]), # reduce form for isolated
    rbind(SQ14$diagnostics[paste0("Kleibergen-Paap rk Wald"), "statistic"], NA), # KP rank stat
    rbind(nIRQ14$gmm$Jtest["p-value"], NA), # p-value for Sargan
    rbind(t(TEcomp[c("Test.ntau=3.4", "Test.ntau=4.5")]), NA))) %>%  # Encompassing, ntau = 4 against ntau = 5  
      mutate(across(where(is.numeric), ~ ifelse(is.na(.), NA, sprintf("%.3f", .)))) %>%  # Ensures exactly 3 decimals
      mutate(across(everything(), ~ ifelse(
        is.na(.), NA,
        ifelse(row_number() %% 2 == 0, paste0("(", trimws(.), ")"), .)
      ))))  # Parentheses without spaces 
  T6.2[1, 1] <- OUTCOME[k]
  
  # Full results
  ecol    <- c("Estimate", "Std. Error", "Pr(>|t|)") 
  # Quantile model
  Qtl     <- list()
  for (x in 3:5) {
    SQ1      <- get(paste0("SQ1", x))
    SQ2      <- get(paste0("SQ2", x))
    RQ1      <- get(paste0("nIRQ1", x))
    if (x == 4) { # because diagnostics are available
      # Structural model
      # Z1
      SQ1    <- rbind(t(SQ1$coefficients[c(paste0("y_q", 1:x), "y_q(spillover)", "y_q(conformity)"), ecol]),
                      t(c(SQ1$diagnostics[paste0("Kleibergen-Paap rk Wald"), "statistic"], rep(NA, 1 + x))), 
                      t(c(SQ1$diagnostics[paste0("Kleibergen-Paap rk Wald"), "df1"], rep(NA, 1 + x))),
                      t(c(SQ1$diagnostics[paste0("Kleibergen-Paap rk Wald"), "p-value"], rep(NA, 1 + x))),
                      t(c(SQ1$gmm$Jtest["p-value"], rep(NA, 1 + x))),
                      matrix(NA, 2, 2 + x))
      # Z1 and Z2
      SQ2    <- rbind(t(SQ2$coefficients[c(paste0("y_q", 1:x), "y_q(spillover)", "y_q(conformity)"), ecol]),
                      t(c(SQ2$diagnostics[paste0("Kleibergen-Paap rk Wald"), "statistic"], rep(NA, 1 + x))), 
                      t(c(SQ2$diagnostics[paste0("Kleibergen-Paap rk Wald"), "df1"], rep(NA, 1 + x))),
                      t(c(SQ2$diagnostics[paste0("Kleibergen-Paap rk Wald"), "p-value"], rep(NA, 1 + x))),
                      t(c(SQ2$gmm$Jtest["p-value"], rep(NA, 1 + x))),
                      cbind(get(paste0("TVSQ2", x)), matrix(NA, 2, 1 + x)))
      
      # Reduced form
      RQ1    <- rbind(t(RQ1$coefficients[paste0("y_q", 1:x), ecol]),
                      t(c(RQ1$diagnostics[paste0("Kleibergen-Paap rk Wald"), "statistic"], rep(NA, x - 1))), 
                      t(c(RQ1$diagnostics[paste0("Kleibergen-Paap rk Wald"), "df1"], rep(NA, x - 1))),
                      t(c(RQ1$diagnostics[paste0("Kleibergen-Paap rk Wald"), "p-value"], rep(NA, x - 1))),
                      t(c(RQ1$gmm$Jtest["p-value"], rep(NA, x - 1))),
                      matrix(NA, 2, x))
    } else {
      # Structural model
      # Z1
      SQ1    <- rbind(t(SQ1$coefficients[c(paste0("y_q", 1:x), "y_q(spillover)", "y_q(conformity)"), ecol]),
                      matrix(NA, 3, 2 + x),
                      t(c(SQ1$gmm$Jtest["p-value"], rep(NA, 1 + x))),
                      matrix(NA, 2, 2 + x))
      # Z1 and Z2
      SQ2    <- rbind(t(SQ2$coefficients[c(paste0("y_q", 1:x), "y_q(spillover)", "y_q(conformity)"), ecol]),
                      matrix(NA, 3, 2 + x),
                      t(c(SQ2$gmm$Jtest["p-value"], rep(NA, 1 + x))),
                      cbind(get(paste0("TVSQ2", x)), matrix(NA, 2, 1 + x)))
      
      # Reduced form
      RQ1    <- rbind(t(RQ1$coefficients[paste0("y_q", 1:x), ecol]),
                      matrix(NA, 3, x),
                      t(c(RQ1$gmm$Jtest["p-value"], rep(NA, x - 1))),
                      matrix(NA, 2, x))
    }
    

    # Monotonocity
    Tmo    <- rbind(t(get(paste0("TM1", x))),
                    matrix(NA, 8, 3))
    
    # Put result together
    Qtlx    <- NULL
    
    if (x == 4) {
      # Encompassing test
      Tec  <- rbind(t(TEcomp),
                      matrix(NA, 8, 3))
      Qtlx <- cbind(SQ1, Id = NA, SQ2, Id = NA, Tmo, Id = NA, Tec, Id = NA, RQ1, Id = NA)
    } else {
      Qtlx <- cbind(SQ1, Id = NA, SQ2, Id = NA, Tmo, Id = NA, RQ1, Id = NA)
    }
    Qtl[[x - 2]]  <- Qtlx
  }

  # LIM
  # Structural model
  SLM       <- rbind(t(SLIM$coefficients[c("G(spillover):y", "G(conformity):y"), ecol]),
                     t(c(SLIM$diagnostics[paste0("Kleibergen-Paap rk Wald"), "statistic"], NA)), 
                     t(c(SLIM$diagnostics[paste0("Kleibergen-Paap rk Wald"), "df1"], NA)),
                     t(c(SLIM$diagnostics[paste0("Kleibergen-Paap rk Wald"), "p-value"], NA)),
                     t(c(SLIM$diagnostics["Hansen J", "p-value"], NA)),
                     matrix(NA, 2, 2))
  
  # Reduced form
  RLM       <- rbind(t(nIRLIM$coefficients["G:y", ecol, drop = FALSE]),
                     nIRLIM$diagnostics[paste0("Kleibergen-Paap rk Wald"), "statistic"], 
                     SLIM$diagnostics[paste0("Kleibergen-Paap rk Wald"), "df1"],
                     SLIM$diagnostics[paste0("Kleibergen-Paap rk Wald"), "p-value"],
                     nIRLIM$diagnostics["Hansen J", "p-value"],
                     matrix(NA, 2, 1))
  
  # CES
  # Structural model
  SCE       <- rbind(t(SCES$coefficients[c("rho", "G(spillover):y", "G(conformity):y"), ecol]),
                   matrix(NA, 6, 3))
  
  # Reduced form
  RCE       <- rbind(t(nIRCES$coefficients[c("rho", "G:y"), ecol]),
                     matrix(NA, 6, 2))
  
  out           <- cbind(Id = NA, Id = NA, do.call(cbind, Qtl), SLM, Id = NA, RLM, 
                         Id = NA, SCE, Id = NA, RCE)
  tp            <- matrix(NA, 1, ncol(out))
  out           <- as.data.frame(rbind(tp, out, tp))
  out[1, 1]     <- OUTCOME[k]
  out[2:10, 2]  <- c("Mean", "StD", "Prob", "KP rk - Stat", "KP rk - df", "KP rk - pvalue", 
                    "Sargan", "Exo Z2 Sargan", "Exo Z2 Wald")
  list(T6.1 = T6.1, T6.2 = T6.2, Full = out)
}

